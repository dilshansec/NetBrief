const {chromium}=require(process.env.NETSENTRY_PLAYWRIGHT);
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8000');
 assert.equal(await page.locator('#navigation, #explorer, #protocol-filter').count(),0);
 await page.locator('.sample-options>summary').click();
 await page.locator('#lab-select').selectOption('port_scan');
 await page.locator('#lab-load').click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent==='Analysis complete.');
 assert.equal(await page.locator('#metrics .metric').nth(1).locator('strong').innerText(),'1');
 assert.equal(await page.locator('#metrics .metric').nth(3).locator('strong').innerText(),'30');
 await page.screenshot({path:'workspace-basic.png',fullPage:true});

 assert.equal(await page.locator('#alerts .finding').count(),1);
 await page.locator('#alerts .finding>summary').click();
 assert.match(await page.locator('.evidence-references').innerText(),/1, 2, 3/);
 assert.ok(await page.locator('#basic-view').isVisible());
 assert.ok(await page.locator('#threats-view').isVisible());
 assert.ok(await page.evaluate(()=>document.querySelector('#basic-view').getBoundingClientRect().bottom<=document.querySelector('#threats-view').getBoundingClientRect().top));
 await page.screenshot({path:'workspace-threats.png',fullPage:true});
 await page.locator('#coverage-details>summary').click();
 assert.equal(await page.locator('#coverage .coverage').count(),9);
 await page.locator('#reports-details>summary').click();
 assert.match(await page.locator('#report-summary').innerText(),/severity/);
 await page.setViewportSize({width:390,height:844});
 await page.locator('#coverage-details>summary').click();
 await page.locator('#reports-details>summary').click();
 await page.locator('#alerts .finding>summary').click();
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'workspace-mobile.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 await page.locator('#upload-details>summary').click();
 await page.locator('#lab-select').selectOption('normal');
 await page.locator('#lab-load').click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent==='Analysis complete.' && document.querySelector('#filename').textContent==='synthetic-normal.pcap');
 assert.equal(await page.locator('#alerts .finding').count(),0);
 assert.ok(await page.locator('#basic-view').isVisible());
 assert.ok(await page.locator('#threats-view').isVisible());
 assert.deepEqual(errors,[]);
 await page.locator('#upload-details>summary').click();
 assert.equal(await page.locator('#demo').count(),0);
 await page.locator('#lab-select').selectOption('mixed');
 await page.locator('#lab-load').click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent==='Analysis complete.' && document.querySelector('#filename').textContent==='synthetic-mixed.pcap');
 assert.equal(await page.locator('#alerts .finding').count(),4);
 assert.deepEqual(await page.locator('#metrics .metric strong').allTextContents(),['5','3','4','321']);
 assert.deepEqual(await page.locator('#alerts .finding-packets').allTextContents(),['Packets: 31–34','Packets: 60–309','Packets: 1–30','Packets: 35–59']);
 assert.equal(await page.locator('#alerts .finding[open]').count(),0);
 assert.ok(await page.locator('#alerts .finding-packets').first().isVisible());
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.equal(await page.locator('#threat-metrics .metric strong').first().innerText(),'4');
 assert.equal(await page.locator('#threat-metrics .metric strong').nth(1).innerText(),'2');
 assert.equal(await page.locator('#threat-metrics .metric strong').nth(3).innerText(),'4 / 9');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'workspace-mixed-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'workspace-mixed.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Browser checks passed: single page, summary before findings, no packet explorer, scan evidence, coverage, reports, mobile, repeat upload, normal capture and four-activity demo.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
